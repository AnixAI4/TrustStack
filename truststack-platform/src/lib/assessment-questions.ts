export function getIndustryQuestions(industry: string | null): AssessmentQuestion[] {
  if (!industry) return []
  if (industry === 'fintech' || industry === 'bfsi') return FINTECH_QUESTIONS
  if (industry === 'healthtech') return HEALTHTECH_QUESTIONS
  if (industry === 'edtech') return EDTECH_QUESTIONS
  return []
}

// Group questions by section for the assessment UI
export function getQuestionsBySection(section: string): AssessmentQuestion[] {
  return ASSESSMENT_QUESTIONS.filter(q => q.section === section)
}

// Get a question by ID
export function getQuestion(id: string): AssessmentQuestion | undefined {
  return ASSESSMENT_QUESTIONS.find(q => q.id === id)
}
