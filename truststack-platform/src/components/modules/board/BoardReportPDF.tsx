function fmtDate(iso: string): string {
  return new Date(iso).toLocaleDateString('en-IN', { day: '2-digit', month: 'short', year: 'numeric' })
}

function Footer({ generatedAt }: { generatedAt: string }) {
  return (
    <Text style={styles.footer} fixed>
      Generated by TrustStack™ | {fmtDate(generatedAt)} | Confidential
    </Text>
  )
}

function GapList({ items, color, empty }: { items: BoardReportGapItem[]; color: string; empty: string }) {
  if (!items.length) return <Text style={styles.emptyNote}>{empty}</Text>
  return (
    <View>
      {items.map((g, i) => (
        <View key={i} style={[styles.gapItem, { borderLeftColor: color }]}>
          <Text style={styles.gapTitle}>{g.title}</Text>
          <Text style={styles.gapAction}>
            {g.action}
            {g.module ? `  →  ${g.module}` : ''}
          </Text>
        </View>
      ))}
    </View>
  )
}

function BoardReportDocument({ report }: { report: BoardReportData }) {
  const color = report.maturity_level ? MATURITY_LEVELS[report.maturity_level].color : GRAY
  const scoreNum = report.compass_score != null ? String(report.compass_score) : '—'
  const period = `${fmtDate(report.period_from)} – ${fmtDate(report.period_to)}`
  const consentDelta = report.metrics.consent_this_period - report.metrics.consent_last_period
  const c = report.compliance
  const trendColor = report.score_trend == null ? GRAY : report.score_trend >= 0 ? GREEN : RED
  const trendText =
    report.score_trend == null
      ? 'No prior assessment to compare'
      : report.score_trend === 0
        ? 'No change since last assessment'
        : `${report.score_trend > 0 ? '▲ +' : '▼ '}${Math.abs(report.score_trend)} pts since last assessment`

  return (
    <Document
      title={`TrustStack Board Report — ${report.org_name}`}
      author="TrustStack™"
      subject="DPDP Compliance Board Report"
    >
      {/* Page 1 — Status summary */}
      <Page size="A4" style={styles.page}>
        <View style={styles.headerRule}>
          <Text style={styles.eyebrow}>DPDP COMPLIANCE STATUS SUMMARY</Text>
          <Text style={styles.h1}>{report.org_name}</Text>
          <Text style={styles.period}>Report period: {period}</Text>
        </View>

        <View style={styles.scoreWrap}>
          <View style={[styles.scoreBadge, { backgroundColor: color }]}>
            <Text style={styles.scoreNum}>{scoreNum}</Text>
            <Text style={styles.scoreOf}>out of 100</Text>
          </View>
          <View style={styles.scoreMeta}>
            <Text style={styles.maturityText}>
              {report.maturity_level
                ? `Level ${report.maturity_level}: ${report.maturity_label}`
                : 'Not yet assessed'}
            </Text>
            <Text style={[styles.trendText, { color: trendColor }]}>{trendText}</Text>
            <View style={styles.barTrack}>
              <View style={[styles.barFill, { width: `${report.compass_score ?? 0}%`, backgroundColor: color }]} />
            </View>
          </View>
        </View>

        <Text style={styles.summaryLabel}>EXECUTIVE SUMMARY</Text>
        <Text style={styles.summaryText}>{report.summary}</Text>

        <Footer generatedAt={report.generated_at} />
      </Page>

      {/* Page 2 — Module completion */}
      <Page size="A4" style={styles.page}>
        <Text style={styles.pageHeading}>2 · MODULE COMPLETION STATUS</Text>
        <Text style={styles.sectionTitle}>Module Completion Status</Text>
        <View style={styles.tableHeadRow}>
          <Text style={[styles.tableHeadCell, { width: '34%' }]}>MODULE</Text>
          <Text style={[styles.tableHeadCell, { width: '22%' }]}>STATUS</Text>
          <Text style={[styles.tableHeadCell, { width: '26%' }]}>KEY METRIC</Text>
          <Text style={[styles.tableHeadCell, { width: '18%' }]}>UPDATED</Text>
        </View>
        {report.modules.map((m, i) => (
          <View key={i} style={styles.tableRow}>
            <Text style={styles.cellModule}>{m.module}</Text>
            <Text style={styles.cellStatus}>{m.status}</Text>
            <Text style={styles.cellMetric}>{m.metric}</Text>
            <Text style={styles.cellUpdated}>{m.last_updated ?? '—'}</Text>
          </View>
        ))}
        <Footer generatedAt={report.generated_at} />
      </Page>

      {/* Page 3 — Key metrics */}
      <Page size="A4" style={styles.page}>
        <Text style={styles.pageHeading}>3 · KEY METRICS</Text>
        <Text style={styles.sectionTitle}>Key Metrics</Text>
        <View style={styles.cardsRow}>
          <View style={styles.card}>
            <Text style={styles.cardLabel}>Consent records (this period)</Text>
            <Text style={styles.cardValue}>{report.metrics.consent_this_period}</Text>
            <Text style={[styles.cardSub, { color: consentDelta >= 0 ? GREEN : RED }]}>
              {consentDelta >= 0 ? '+' : ''}
              {consentDelta} vs prior period ({report.metrics.consent_last_period})
            </Text>
          </View>
          <View style={styles.card}>
            <Text style={styles.cardLabel}>Grievance complaints</Text>
            <Text style={styles.cardValue}>{report.metrics.complaints_open}</Text>
            <Text style={styles.cardSub}>open · {report.metrics.complaints_resolved} resolved this period</Text>
          </View>
          <View style={styles.cardLast}>
            <Text style={styles.cardLabel}>Unresolved gaps</Text>
            <Text style={styles.cardValue}>{report.metrics.gaps_total}</Text>
            <Text style={[styles.cardSub, { color: RED }]}>{report.metrics.gaps_p0} critical (P0)</Text>
          </View>
        </View>
        <View style={[styles.tableRow, { borderBottomWidth: 0, marginTop: 6 }]}>
          <Text style={{ fontSize: 10, color: GRAY }}>
            Gap breakdown — P0: {report.metrics.gaps_p0} · P1: {report.metrics.gaps_p1} · P2+:{' '}
            {report.metrics.gaps_p2plus}
          </Text>
        </View>
        <Footer generatedAt={report.generated_at} />
      </Page>

      {/* Page 4 — Top priority actions */}
      <Page size="A4" style={styles.page}>
        <Text style={styles.pageHeading}>4 · TOP PRIORITY ACTIONS</Text>
        <Text style={styles.sectionTitle}>Top Priority Actions</Text>
        <Text style={[styles.priLabel, { color: RED }]}>P0 — Must fix immediately</Text>
        <GapList items={report.actions_p0} color={RED} empty="No critical (P0) gaps outstanding." />
        <Text style={[styles.priLabel, { color: AMBER }]}>P1 — Fix within 30 days</Text>
        <GapList items={report.actions_p1} color={AMBER} empty="No P1 gaps outstanding." />
        <Footer generatedAt={report.generated_at} />
      </Page>

      {/* Page 5 — Compliance timeline */}
      <Page size="A4" style={styles.page}>
        <Text style={styles.pageHeading}>5 · COMPLIANCE TIMELINE</Text>
        <Text style={styles.sectionTitle}>Compliance Timeline</Text>
        <View style={styles.timelineCols}>
          <View style={styles.timelineCol}>
            <Text style={[styles.timelineColTitle, { color: GREEN }]}>Completed this period</Text>
            {report.timeline.filter(t => t.kind === 'completed').length ? (
              report.timeline
                .filter(t => t.kind === 'completed')
                .map((t, i) => (
                  <Text key={i} style={styles.timelineItem}>
                    {t.label}
                    {t.date ? <Text style={styles.timelineDate}> — {t.date}</Text> : null}
                  </Text>
                ))
            ) : (
              <Text style={[styles.timelineItem, { color: MUTED }]}>No completed milestones in this period.</Text>
            )}
          </View>
          <View style={styles.timelineCol}>
            <Text style={[styles.timelineColTitle, { color: ACCENT }]}>Upcoming</Text>
            {report.timeline.filter(t => t.kind === 'upcoming').length ? (
              report.timeline
                .filter(t => t.kind === 'upcoming')
                .map((t, i) => (
                  <Text key={i} style={styles.timelineItem}>
                    {t.label}
                    {t.date ? <Text style={styles.timelineDate}> — {t.date}</Text> : null}
                  </Text>
                ))
            ) : (
              <Text style={[styles.timelineItem, { color: MUTED }]}>No upcoming actions scheduled.</Text>
            )}
          </View>
        </View>
        <Footer generatedAt={report.generated_at} />
      </Page>

      {/* Page 6 — Compliance coverage (M5–M8) */}
      <Page size="A4" style={styles.page}>
        <Text style={styles.pageHeading}>6 · COMPLIANCE COVERAGE</Text>
        <Text style={styles.sectionTitle}>Compliance Coverage (DSR · ROPA · Vendors · Breach)</Text>
        <View style={styles.cardsRow}>
          <View style={styles.card}>
            <Text style={styles.cardLabel}>Data Subject Requests (pending)</Text>
            <Text style={styles.cardValue}>{c.dsr.pending}</Text>
            <Text style={[styles.cardSub, { color: c.dsr.overdue > 0 ? RED : GRAY }]}>
              {c.dsr.overdue > 0 ? `${c.dsr.overdue} overdue` : 'none overdue'} · {c.dsr.completed_last_30_days} done in 30d
            </Text>
          </View>
          <View style={styles.cardLast}>
            <Text style={styles.cardLabel}>Processing Activities (active)</Text>
            <Text style={styles.cardValue}>{c.ropa.active_entries}</Text>
            <Text style={[styles.cardSub, { color: c.ropa.last_review_date ? GRAY : RED }]}>
              {c.ropa.last_review_date ? `last DPO review ${fmtDate(c.ropa.last_review_date)}` : 'not yet reviewed'}
            </Text>
          </View>
        </View>
        <View style={styles.cardsRow}>
          <View style={styles.card}>
            <Text style={styles.cardLabel}>Third-Party Vendors</Text>
            <Text style={styles.cardValue}>{c.vendors.total}</Text>
            <Text style={[styles.cardSub, { color: c.vendors.overdue_assessments > 0 ? RED : GRAY }]}>
              {c.vendors.overdue_assessments > 0 ? `${c.vendors.overdue_assessments} with expired DPA` : 'all DPAs current'}
            </Text>
          </View>
          <View style={styles.cardLast}>
            <Text style={styles.cardLabel}>Data Breach Incidents (open)</Text>
            <Text style={styles.cardValue}>{c.breach.open_incidents}</Text>
            <Text style={[styles.cardSub, { color: c.breach.past_dpbi_deadline > 0 ? RED : GRAY }]}>
              {c.breach.past_dpbi_deadline > 0 ? `${c.breach.past_dpbi_deadline} past 72-hr DPBI deadline` : 'none past 72-hr deadline'}
            </Text>
          </View>
        </View>
        {(c.breach.past_dpbi_deadline > 0 || c.dsr.overdue > 0) && (
          <Text style={{ marginTop: 16, fontSize: 10, color: RED, fontFamily: 'Helvetica-Bold' }}>
            {c.breach.past_dpbi_deadline > 0
              ? `CRITICAL: ${c.breach.past_dpbi_deadline} breach incident(s) past the 72-hour DPBI notification deadline — immediate regulatory reporting required.`
              : `ALERT: ${c.dsr.overdue} Data Subject Request(s) overdue past the 30-day DPDP limit.`}
          </Text>
        )}
        <Footer generatedAt={report.generated_at} />
      </Page>
    </Document>
  )
}

export async function renderBoardReportPdf(report: BoardReportData): Promise<Buffer> {
  return renderToBuffer(<BoardReportDocument report={report} />)
}
