export function fallbackEasyText(text: string): string | undefined {
  const normalized = normalizeEasy(text);
  if (normalized.length < 24) return undefined;

  let easy = normalized;
  for (const [pattern, replacement] of FALLBACK_RULES) {
    easy = easy.replace(pattern, replacement);
  }

  if (easy === normalized) return undefined;
  easy = easy.replace(/\s+/g, " ").trim();
  // If the original began with a capital (a sentence/heading) but a swap left a
  // lowercase word at the front, restore the leading capital.
  if (/^[A-Z]/.test(normalized) && /^[a-z]/.test(easy)) {
    easy = easy.charAt(0).toUpperCase() + easy.slice(1);
  }
  return easy;
}
