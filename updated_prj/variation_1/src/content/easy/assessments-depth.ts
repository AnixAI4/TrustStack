const PROTECTED = /(?:₹[\d,.]+(?:\s*(?:crore|lakh))?|\b(?:Section|Sections|Rule|Rules|Schedule|Chapter|Article)\s+(?:\d+[\w(),&.\-]*|[IVXLC]+\b)|\b(?:DPDPA?|GDPR|TDSAT|CERT-In|MeitY|SEBI|AWS|Consent Manager)\b|\b\d{1,2}(?:st|nd|rd|th)?\s+(?:January|February|March|April|May|June|July|August|September|October|November|December),?\s+\d{4}\b|\b\d+(?:\.\d+)?%\b|\b\d+(?:-year|-hour)?s?\b)/g;

function simplify(normal: string): string {
  const protectedTokens: string[] = [];
  let easy = normal.replace(PROTECTED, (token) => {
    protectedTokens.push(token);
    return `\u0000${protectedTokens.length - 1}\u0000`;
  });

  for (const [pattern, replacement] of REPLACEMENTS) {
    easy = easy.replace(pattern, replacement);
  }

  easy = easy
    .replace(/\ba organisation\b/gi, "an organisation")
    .replace(/\ba authority\b/gi, "an authority")
    .replace(/\s+([,.;:?!])/g, "$1")
    .replace(/\s{2,}/g, " ")
    .trim();

  return easy.replace(/\u0000(\d+)\u0000/g, (_, index: string) => protectedTokens[Number(index)]);
}

