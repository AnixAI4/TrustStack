function collectStrings(value: unknown, key = ""): string[] {
  if (typeof value === "string") return HIDDEN_KEYS.has(key) ? [] : [value];
  if (Array.isArray(value)) return value.flatMap((item) => collectStrings(item, key));
  if (!value || typeof value !== "object") return [];

  return Object.entries(value as UnknownRecord).flatMap(([childKey, child]) =>
    HIDDEN_KEYS.has(childKey) ? [] : collectStrings(child, childKey)
  );
}

