'use server'

import { Document, Page, Text, View, StyleSheet, renderToBuffer } from '@react-pdf/renderer'
import { DPDP_BASES, DATA_CATEGORIES, ROPA_SUBJECT_TYPES, ROPA_STATUS_LABELS } from '@/lib/platform/constants'
import type { RopaEntry, RopaConsentCoverage } from '@/types/dpdp'

const styles = StyleSheet.create({
  page: { padding: 40, fontFamily: 'Helvetica', fontSize: 10 },
  title: { fontSize: 18, marginBottom: 20, fontWeight: 'bold', color: '#C9540A' },
  section: { marginBottom: 16 },
  sectionTitle: { fontSize: 12, marginBottom: 8, fontWeight: 'bold', borderBottomWidth: 1, borderBottomColor: '#E5E7EB', paddingBottom: 4 },
  row: { flexDirection: 'row', marginBottom: 4 },
  label: { width: 140, color: '#6B7280', fontWeight: 'bold' },
  value: { flex: 1, color: '#1F2937' },
  entry: { marginBottom: 20, padding: 12, backgroundColor: '#F9FAFB', borderRadius: 4 },
  entryTitle: { fontSize: 11, fontWeight: 'bold', color: '#C9540A', marginBottom: 8 },
  badge: { fontSize: 8, padding: '2 6', borderRadius: 4, backgroundColor: '#E5E7EB', color: '#374151' },
  footer: { position: 'absolute', bottom: 30, left: 40, right: 40, fontSize: 8, color: '#9CA3AF', textAlign: 'center' },
})

function basisLabel(v: string): string {
  return DPDP_BASES.find(basis => basis.id === v)?.label ?? v
}
function categoryLabel(key: string): string {
  return DATA_CATEGORIES.find(c => c.key === key)?.label ?? key
}
function subjectLabel(v: string): string {
  return ROPA_SUBJECT_TYPES.find(s => s.value === v)?.label ?? v
}
function statusLabel(v: string): string {
  return ROPA_STATUS_LABELS[v as keyof typeof ROPA_STATUS_LABELS] ?? v
}
function consentLabel(c?: RopaConsentCoverage): string {
  if (!c) return 'Not assessed'
  if (c.status === 'configured') return 'Configured'
  if (c.status === 'missing') return 'Consent gap'
  return 'Not applicable'
}

interface Props {
  orgName: string
  entries: RopaEntry[]
  coverage?: Record<string, RopaConsentCoverage>
  generatedAt?: Date
}

function RopaDocument({ orgName, entries, coverage = {}, generatedAt = new Date() }: Props) {
  return (
    <Document>
      <Page size="A4" style={styles.page}>
        <Text style={styles.title}>Record of Processing Activities</Text>
        <View style={styles.section}>
          <View style={styles.row}>
            <Text style={styles.label}>Organisation</Text>
            <Text style={styles.value}>{orgName}</Text>
          </View>
          <View style={styles.row}>
            <Text style={styles.label}>Generated</Text>
            <Text style={styles.value}>{generatedAt.toLocaleDateString('en-IN', { day: 'numeric', month: 'long', year: 'numeric' })}</Text>
          </View>
          <View style={styles.row}>
            <Text style={styles.label}>Total entries</Text>
            <Text style={styles.value}>{entries.length}</Text>
          </View>
        </View>

        {entries.map((e, idx) => (
          <View key={e.id} style={styles.entry} wrap={false}>
            <Text style={styles.entryTitle}>{idx + 1}. {e.activity_name}</Text>
            <View style={styles.row}>
              <Text style={styles.label}>Purpose</Text>
              <Text style={styles.value}>{e.processing_purposes.join(', ') || ' - '}</Text>
            </View>
            <View style={styles.row}>
              <Text style={styles.label}>Legal basis</Text>
              <Text style={styles.value}>{basisLabel(e.legal_basis)}</Text>
            </View>
            <View style={styles.row}>
              <Text style={styles.label}>Data categories</Text>
              <Text style={styles.value}>{e.data_categories?.map(categoryLabel).join(', ') || ' - '}</Text>
            </View>
            <View style={styles.row}>
              <Text style={styles.label}>Data subjects</Text>
              <Text style={styles.value}>{e.data_subject_types?.map(subjectLabel).join(', ') || ' - '}</Text>
            </View>
            <View style={styles.row}>
              <Text style={styles.label}>Retention</Text>
              <Text style={styles.value}>{e.retention_period || ' - '}</Text>
            </View>
            <View style={styles.row}>
              <Text style={styles.label}>Consent coverage</Text>
              <Text style={styles.value}>{consentLabel(coverage[e.id])}</Text>
            </View>
            <View style={styles.row}>
              <Text style={styles.label}>Status</Text>
              <Text style={styles.value}>{statusLabel(e.status)}</Text>
            </View>
          </View>
        ))}

        <Text style={styles.footer}>
          Generated by TrustStack · DPDP 2023 compliant · Page 1
        </Text>
      </Page>
    </Document>
  )
}

export async function generateRopaReportPdf(props: Props): Promise<Buffer> {
  return renderToBuffer(<RopaDocument {...props} />)
}
