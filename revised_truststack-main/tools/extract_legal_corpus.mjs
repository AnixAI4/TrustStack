#!/usr/bin/env node
/**
 * Slice 11 Stage 1a (SLICE_11 §4.2): the AI assistant's legal corpus — the DPDP
 * Act 2023 and the DPDP Rules 2025 (G.S.R. 846(E)) with the corrigendum
 * G.S.R. 892(E) applied — extracted ONCE from the Gazette PDFs in docs/legal/
 * into apps/web/lib/ai/corpus/legal-text.ts, which is committed. CI has no
 * pdftotext; it checks the committed file's hash instead
 * (tests/unit/ai-corpus.test.ts), so a hand edit fails the build.
 *
 * An amendment or a new corrigendum is a NEW version: add the PDF to
 * docs/legal/, extend this script, re-run it and commit both. Every draft
 * stores the version it was grounded on.
 *
 *   node tools/extract_legal_corpus.mjs           # write the module
 *   node tools/extract_legal_corpus.mjs --check   # exit 1 if it would change
 */
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const OUT = "apps/web/lib/ai/corpus/legal-text.ts";
const pdf = (file) => execFileSync("pdftotext", [`docs/legal/${file}`, "-"], { encoding: "utf8" });

/** Page furniture of the Gazette, never part of the text. */
const FURNITURE = [
  /^THE GAZETTE OF INDIA\s*:?\s*EXTRAORDINARY$/,
  /^\[PART II\s*—\s*(SEC\. 3\(i\)\])?$/,
  /^\[PART II—$/,
  /^SEC\. 1\]$/,
  /^\d{1,3}$/,
  // The Hindi running heads of the bilingual Gazette ("[भाग II—खण्ड 3(i)]"): the English text has no Devanagari.
  /[\u0900-\u097F]/u,
  /^\f/,
];

function clean(text, startMarker, endMarker) {
  const start = text.indexOf(startMarker);
  if (start < 0) throw new Error(`start marker not found: ${startMarker}`);
  const end = endMarker ? text.indexOf(endMarker, start) : -1;
  const body = text.slice(start, end < 0 ? undefined : end);
  const lines = body
    .replace(/\f/g, "\n")
    .split("\n")
    .map((l) => l.replace(/\s+$/, ""))
    .filter((l) => !FURNITURE.some((re) => re.test(l.trim())));
  // Collapse runs of blank lines.
  return lines.join("\n").replace(/\n{3,}/g, "\n\n").trim() + "\n";
}

const act = clean(pdf("DPDP_Act_2023.pdf"), "THE DIGITAL PERSONAL DATA PROTECTION ACT, 2023");
let rules = clean(pdf("DPDP_Rules_2025.pdf"), "MINISTRY OF ELECTRONICS AND INFORMATION TECHNOLOGY");
const corrigendumRaw = pdf("DPDP_Rules_2025_Corrigendum_GSR892E.pdf");
const corrigendum = clean(corrigendumRaw, "G.S.R. 892(E)", "[F. No.");

/**
 * G.S.R. 892(E), applied where its target is unambiguous in the English text.
 * Each entry: the corrigendum's own words, the text before, the text after,
 * and how many occurrences it must find (it refuses to guess).
 */
const CORRECTIONS = [
  ["(i)(a)–(b): rule 1(3)–(4), “of this Gazette” → “in the Official Gazette”", /publication(\s+)of this Gazette/g, "publication$1in the Official Gazette", 2],
  ["(ii): rule 13(5), “Department” → “Departments”", /Ministries or Department of the Central Government/g, "Ministries or Departments of the Central Government", 1],
  ["(iii): rule 23(1), “given in such” → “given in such order”", /may be given in such\./g, "may be given in such order.", 1],
  ["(iv)(a): “everybody” → “every body”", /everybody/g, "every body", 1],
  ["(iv)(b): “(18 or 2013)” → “(18 of 2013)”", /\(18 or 2013\)/g, "(18 of 2013)", 1],
];
const applied = [];
const notApplied = ["(v): a Schedule's “.” → “;” and “(a) to (f)” → “(a) to (g)” — its line positions do not survive extraction"];
for (const [label, pattern, replacement, expected] of CORRECTIONS) {
  const count = (rules.match(pattern) ?? []).length;
  if (count !== expected) {
    notApplied.push(`${label} — found ${count}, expected ${expected}`);
    continue;
  }
  rules = rules.replace(pattern, replacement);
  applied.push(`${label} (×${count})`);
}

const sources = [
  "docs/legal/DPDP_Act_2023.pdf",
  "docs/legal/DPDP_Rules_2025.pdf",
  "docs/legal/DPDP_Rules_2025_Corrigendum_GSR892E.pdf",
];
const hash = createHash("sha256").update(act).update("\u0000").update(rules).update("\u0000").update(corrigendum).digest("hex");
const version = `dpdp-act-2023+rules-2025+gsr892e/${hash.slice(0, 12)}`;

const banner = `/**
 * GENERATED by tools/extract_legal_corpus.mjs — do not edit by hand.
 * tests/unit/ai-corpus.test.ts recomputes LEGAL_CORPUS_SHA256 and fails on any edit.
 *
 * The DPDP Act 2023 and the DPDP Rules 2025 (G.S.R. 846(E)), from:
${sources.map((s) => ` *   ${s}`).join("\n")}
 * G.S.R. 892(E) applied where unambiguous:
${applied.map((s) => ` *   ✓ ${s}`).join("\n")}
${notApplied.map((s) => ` *   ✗ not applied (its words are printed below the Rules instead): ${s}`).join("\n")}
 */
`;

const module = `${banner}import "server-only";

export const LEGAL_CORPUS_VERSION = ${JSON.stringify(version)};
export const LEGAL_CORPUS_SHA256 = ${JSON.stringify(hash)};

export const ACT_TEXT = ${JSON.stringify(act)};

export const RULES_TEXT = ${JSON.stringify(rules)};

export const CORRIGENDUM_TEXT = ${JSON.stringify(corrigendum)};
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(OUT, "utf8");
  if (current !== module) {
    console.log(`::error::${OUT} is out of date — run node tools/extract_legal_corpus.mjs`);
    process.exit(1);
  }
  console.log(`legal corpus: up to date (${version})`);
} else {
  writeFileSync(OUT, module);
  const words = (s) => s.split(/\s+/).filter(Boolean).length;
  console.log(`wrote ${OUT}: ${version}`);
  console.log(`  Act ${words(act)} words · Rules ${words(rules)} words · corrigendum ${words(corrigendum)} words`);
  for (const s of applied) console.log(`  applied ${s}`);
  for (const s of notApplied) console.log(`  NOT applied ${s}`);
}
