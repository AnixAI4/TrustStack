#!/usr/bin/env node
/**
 * Regenerates apps/web/lib/supabase/database.types.ts from a migrated database.
 *
 *   pnpm db:types            # hosted dev project (DIRECT_URL from .env.local)
 *   pnpm db:types --check    # CI: fail if the committed file is stale
 *
 * The Supabase CLI runs postgres-meta in Docker, so Docker must be running.
 * CI passes the local stack's DB_URL as DIRECT_URL (D-018).
 */
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const out = path.join(root, "apps/web/lib/supabase/database.types.ts");
const envFile = path.join(root, ".env.local");

if (!process.env.DIRECT_URL && existsSync(envFile)) {
  const line = readFileSync(envFile, "utf8").split("\n").find((l) => l.startsWith("DIRECT_URL="));
  if (line) process.env.DIRECT_URL = line.slice("DIRECT_URL=".length).trim();
}
if (!process.env.DIRECT_URL) throw new Error("DIRECT_URL is not set");

const cliVersion = process.env.SUPABASE_CLI_VERSION ?? "2.117.0";
const header =
  "// GENERATED by `pnpm db:types` from the migrated schema — do not edit by hand.\n" +
  "// CI regenerates it from an empty database and fails if this file is stale.\n\n";

const generated = execFileSync(
  "npx",
  ["-y", `supabase@${cliVersion}`, "gen", "types", "typescript", "--db-url", process.env.DIRECT_URL, "--schema", "public"],
  { encoding: "utf8", stdio: ["ignore", "pipe", "inherit"], maxBuffer: 16 * 1024 * 1024 },
);
const next = header + generated.trimEnd() + "\n";

if (process.argv.includes("--check")) {
  const current = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (current !== next) {
    console.log("::error::database.types.ts is stale — run `pnpm db:types` and commit it");
    writeFileSync("/tmp/database.types.generated.ts", next);
    process.exit(1);
  }
  console.log("database.types.ts: up to date");
} else {
  writeFileSync(out, next);
  console.log(`wrote ${path.relative(root, out)}`);
}
